export const getTour = (slug: string) => tours.find((t) => t.slug === slug);
export const popularTours = tours.filter((t) => t.popular);
export type LengthId = "short" | "medium" | "long";
/** Catalog length buckets: 4–6, 7–10 and 11–20 days. */
export const lengthOf = (days: number): LengthId => (days <= 6 ? "short" : days <= 10 ? "medium" : "long");

export const maxTourPrice = Math.max(...tours.map((t) => t.prices.standard));

/** "Day 3" or "Days 3–4" for each itinerary stop. */
export function dayLabels(tour: Tour) {
  let day = 1;
  return tour.itinerary.map((s) => {
    const span = s.days ?? 1;
    const label = span > 1 ? `${day}–${day + span - 1}` : `${day}`;
    day += span;
    return { label, multi: span > 1 };
  });
}
